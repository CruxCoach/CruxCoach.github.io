/** Pick the page language: the document's own `lang`, else the browser's. */
export function detectLanguage(doc = globalThis.document, nav = globalThis.navigator) {
  const declared = doc?.documentElement?.lang;
  if (declared && LANGUAGES.includes(declared.slice(0, 2))) return declared.slice(0, 2);
  const preferred = (nav?.language || 'en').slice(0, 2).toLowerCase();
  return LANGUAGES.includes(preferred) ? preferred : 'en';
}

export function createTranslator(language) {
  const table = STRINGS[language] || STRINGS.en;
  return function translate(key, values) {
    // Falling back to English is better than showing a raw key, but a missing
    // German string is a bug rather than a feature — the parity test catches it.
    let text = table[key] ?? STRINGS.en[key];
    if (text === undefined) return key;
    if (values) {
      for (const [name, value] of Object.entries(values)) {
        text = text.split(`{${name}}`).join(String(value));
      }
    }
    return text;
  };
}

/** Render a reducer rejection as a sentence. */
export function describeRejection(translate, rejection) {
  return translate('rejection.prefix', {
    seq: rejection.seq,
    reason: translate(`rejection.${rejection.code}`),
  });
}

